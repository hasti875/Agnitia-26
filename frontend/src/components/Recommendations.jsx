import { Section, Pill } from './ui'
import { fmtInt, fmtNum } from '../format'

export function Recommendations({ recommendations, loading, error, onRetry }) {
  const rec = recommendations
  const movements = rec?.movements ?? []

  return (
    <Section
      id="optimizer"
      title="Optimizer Recommendations"
      subtitle="Suggested resource transfers generated by the Phase 6 OR-Tools optimizer to balance risk across regions."
      loading={loading}
      error={error}
      onRetry={onRetry}
      isEmpty={!loading && !error && movements.length === 0}
    >
      {rec?.feasible === false ? (
        <p className="muted">The optimizer reported no feasible solution for the current state.</p>
      ) : (
        <>
          <div className="stat-grid">
            <Pill label="Total Units Moved" value={fmtInt(rec?.total_resources_moved)} tag="Transfer Units" tone="teal" />
            <Pill label="Number of Transfers" value={fmtInt(movements.length)} tag="Logistics Routes" tone="teal" />
            <Pill label="Estimated Move Cost" value={fmtNum(rec?.total_movement_cost)} tag="Cost Units" tone="ok" />
            <Pill label="Remaining Deficit" value={fmtInt(rec?.remaining_deficit)} tag={rec?.remaining_deficit > 0 ? 'Shortage' : '✓ Cleared'} tone={rec?.remaining_deficit > 0 ? 'danger' : 'ok'} />
          </div>

          <div style={{ marginTop: '20px' }}>
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th scope="col">From (Donor Region)</th>
                    <th scope="col">To (Recipient Ward)</th>
                    <th scope="col">Resource Type</th>
                    <th scope="col" style={{ textAlign: 'right' }}>Quantity</th>
                    <th scope="col" style={{ textAlign: 'right' }}>Distance (km)</th>
                    <th scope="col" style={{ textAlign: 'right' }}>Move Cost</th>
                    <th scope="col">Optimization Rationale</th>
                  </tr>
                </thead>
                <tbody>
                  {movements.map((m, i) => (
                    <tr key={i}>
                      <td className="label" style={{ color: '#0d9488' }}>{m.from_area}</td>
                      <td className="label" style={{ color: '#0f172a' }}>{m.to_area}</td>
                      <td style={{ textTransform: 'capitalize' }}>{m.resource.replace(/_/g, ' ')}</td>
                      <td className="num" style={{ fontWeight: 800 }}>{fmtInt(m.quantity)}</td>
                      <td className="num">{fmtNum(m.distance_km, 0)} km</td>
                      <td className="num">{fmtNum(m.movement_cost)}</td>
                      <td className="muted" style={{ fontSize: '0.82rem', maxWidth: '320px' }}>{m.reason}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </>
      )}
    </Section>
  )
}

export default Recommendations

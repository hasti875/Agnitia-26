"""
features.py
===========
Phase 4 — feature engineering for the 6-hour flood-risk forecast.

WHAT THIS MODULE DOES
---------------------
Turns the raw hourly rows in ``climate_history.csv`` into a supervised
learning table:

    features available at time T   →   target = flood_risk at time T + 6h

One row = one region at one hour.

FEATURES (all computed only from information available at or before T)
-----------------------------------------------------------------------
    rainfall_last_1h      rainfall_mm at T
    rainfall_last_3h      rolling sum of rainfall over T-2..T
    rainfall_last_6h      rolling sum of rainfall over T-5..T
    rainfall_trend        rainfall at T minus rainfall at T-3
                          (positive = rain intensifying)
    river_level           river_level_m at T
    river_level_change    river level at T minus level at T-1
    river_level_trend     river level at T minus level at T-3
    temperature           temperature_c at T
    humidity              humidity at T
    historical_flood_frequency   static per region
    population            static per region
    population_density    static per region
    vulnerability_index   static per region
    road_accessibility    static per region

TARGET
------
    future_flood_risk = flood_risk.shift(-6) within each area.
    So features at T are paired with the risk that occurs 6 hours later.

LEAKAGE RULES
-------------
1. Rolling windows end AT T (inclusive) — never after T.
2. The target is the only column taken from the future (T + 6h).
3. Splitting is chronological (see ``split_chronological``) — the model is
   never tested on data it has already seen in training.

SYNTHETIC DATA DISCLAIMER
-------------------------
climate_history.csv is 100% synthetic (generated by backend/data/generate_data.py).
Every model trained from it is a PROTOTYPE DEMONSTRATION ONLY and must not be
presented as an operational flood-forecasting system.
"""

from __future__ import annotations

import os
from typing import Dict, List, Optional, Tuple

import pandas as pd

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

_HERE          = os.path.dirname(os.path.abspath(__file__))
_BACKEND_DIR   = os.path.dirname(_HERE)
DATA_DIR       = os.path.join(_BACKEND_DIR, "data")
MODELS_DIR     = os.path.join(_HERE, "models")

CLIMATE_CSV    = os.path.join(DATA_DIR, "climate_history.csv")
MODEL_PATH     = os.path.join(MODELS_DIR, "flood_risk_model.pkl")
METADATA_PATH  = os.path.join(MODELS_DIR, "model_metadata.json")

# ---------------------------------------------------------------------------
# Forecast configuration
# ---------------------------------------------------------------------------

FORECAST_HORIZON_HOURS = 6

FEATURE_COLUMNS: List[str] = [
    "rainfall_last_1h",
    "rainfall_last_3h",
    "rainfall_last_6h",
    "rainfall_trend",
    "river_level",
    "river_level_change",
    "river_level_trend",
    "temperature",
    "humidity",
    "historical_flood_frequency",
    "population",
    "population_density",
    "vulnerability_index",
    "road_accessibility",
]

TARGET_COLUMN = "future_flood_risk"

RAW_COLUMNS = [
    "timestamp", "area_id", "area_name", "rainfall_mm", "river_level_m",
    "temperature_c", "humidity", "historical_flood_frequency", "population",
    "population_density", "vulnerability_index", "road_accessibility",
    "flood_risk",
]


# ---------------------------------------------------------------------------
# Feature builder
# ---------------------------------------------------------------------------

def build_feature_frame(
    csv_path:  str = CLIMATE_CSV,
    with_target: bool = True,
) -> pd.DataFrame:
    """
    Load climate_history.csv and build the supervised learning table.

    Parameters
    ----------
    csv_path    : Path to the synthetic climate CSV.
    with_target : True  → add `future_flood_risk` (T + 6h) and drop rows where
                          the future is unknown (the last 6 hours per area).
                  False → features only; keeps the most recent rows so the
                          model can forecast "now". Used by predict.py.

    Returns
    -------
    DataFrame sorted by (area_id, timestamp) containing the raw columns
    needed downstream, all FEATURE_COLUMNS, and optionally TARGET_COLUMN.
    """
    df = pd.read_csv(csv_path, parse_dates=["timestamp"])
    df = df.sort_values(["area_id", "timestamp"]).reset_index(drop=True)

    # Grouped operations — every rolling/lag stays INSIDE one region.
    by_area = df.groupby("area_id", sort=False)
    rain    = df["rainfall_mm"]
    river   = df["river_level_m"]

    out = pd.DataFrame({
        "timestamp":   df["timestamp"],
        "area_id":     df["area_id"],
        "area_name":   df["area_name"],
        # --- rainfall ---
        "rainfall_last_1h": rain,
        "rainfall_last_3h": by_area["rainfall_mm"].transform(
            lambda s: s.rolling(3, min_periods=1).sum()),
        "rainfall_last_6h": by_area["rainfall_mm"].transform(
            lambda s: s.rolling(6, min_periods=1).sum()),
        "rainfall_trend": rain - by_area["rainfall_mm"].transform(
            lambda s: s.shift(3)),
        # --- river ---
        "river_level": river,
        "river_level_change": river - by_area["river_level_m"].transform(
            lambda s: s.shift(1)),
        "river_level_trend": river - by_area["river_level_m"].transform(
            lambda s: s.shift(3)),
        # --- weather ---
        "temperature": df["temperature_c"],
        "humidity":    df["humidity"],
        # --- static regional attributes ---
        "historical_flood_frequency": df["historical_flood_frequency"],
        "population":          df["population"],
        "population_density":  df["population_density"],
        "vulnerability_index": df["vulnerability_index"],
        "road_accessibility":  df["road_accessibility"],
    })

    if with_target:
        # Target: the SAME column, 6 hours later, within the same region.
        out[TARGET_COLUMN] = by_area["flood_risk"].transform(
            lambda s: s.shift(-FORECAST_HORIZON_HOURS))
        # Rows whose future is unknown (last 6 h per area) or whose lag
        # features are undefined (first 3 h per area) are not usable.
        out = out.dropna(subset=FEATURE_COLUMNS + [TARGET_COLUMN])
    else:
        # Features only: drop the first 3 hours of each region (lags undefined)
        # but KEEP the latest rows so we can forecast from "now".
        out = out.dropna(subset=FEATURE_COLUMNS)

    return out.reset_index(drop=True)


# ---------------------------------------------------------------------------
# Chronological train / test split
# ---------------------------------------------------------------------------

def split_chronological(
    frame:       pd.DataFrame,
    test_ratio:  float = 0.2,
    cutoff:      Optional[pd.Timestamp] = None,
) -> Tuple[pd.DataFrame, pd.DataFrame, Dict[str, str]]:
    """
    Split the feature frame by TIME (never randomly).

    Training = earlier period, Test = later period.
    If `cutoff` is supplied (e.g. reloaded from model_metadata.json) that exact
    timestamp is reused so evaluation is reproducible.

    Returns
    -------
    (train_df, test_df, split_info)
    """
    if cutoff is None:
        times = pd.DatetimeIndex(sorted(frame["timestamp"].unique()))
        split_index = int(len(times) * (1.0 - test_ratio))
        split_index = min(max(split_index, 1), len(times) - 1)
        cutoff = times[split_index]
    else:
        cutoff = pd.Timestamp(cutoff)

    train_df = frame[frame["timestamp"] <  cutoff].reset_index(drop=True)
    test_df  = frame[frame["timestamp"] >= cutoff].reset_index(drop=True)

    if train_df.empty or test_df.empty:
        raise ValueError(
            "Chronological split produced an empty set — check the data range."
        )

    info = {
        "cutoff":       str(cutoff),
        "train_start":  str(train_df["timestamp"].min()),
        "train_end":    str(train_df["timestamp"].max()),
        "test_start":   str(test_df["timestamp"].min()),
        "test_end":     str(test_df["timestamp"].max()),
        "n_train_rows": str(len(train_df)),
        "n_test_rows":  str(len(test_df)),
    }
    return train_df, test_df, info


# ---------------------------------------------------------------------------
# Convenience: one feature row per region, latest available
# ---------------------------------------------------------------------------

def latest_feature_rows(
    csv_path:  str = CLIMATE_CSV,
    as_of:     Optional[pd.Timestamp] = None,
) -> pd.DataFrame:
    """
    Return the most recent feature row (≤ `as_of`) for every region.
    Used by predict.py — no target column is required here.
    """
    frame = build_feature_frame(csv_path=csv_path, with_target=False)
    if as_of is not None:
        frame = frame[frame["timestamp"] <= pd.Timestamp(as_of)]

    rows = (
        frame.sort_values("timestamp")
             .groupby("area_id", sort=False)
             .tail(1)
             .reset_index(drop=True)
    )
    if rows.empty:
        raise ValueError("No feature rows available at or before the cutoff.")
    return rows
